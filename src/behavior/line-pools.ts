// 下一次重抽**必然**接上它，于是她像在把一件事说完，而不是每隔几秒换一句不相干的话。
//
// 桥接池按 `from>to` 索引：状态**切换**时优先从那里抽一句把上一句接住。
//
// 文案在 src/labels/lines/{zh,en}.ts。原本的契约文档（docs/）与漂移守卫（test/）都已删除，
